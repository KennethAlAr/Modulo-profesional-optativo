# Creamos una lista:

mi_lista = [10, 25, 30, 40, 50]

# Se imprime un elemento de la lista
print(mi_lista[0])

mi_lista[1] = 999 # Con este comando podemos modificar el dato de la posición indicada.
print(mi_lista[1])

print(len(mi_lista)) # Así podemos ver el largo de la lista.

mi_lista.append(60) # Así podemos agregar un valor al final de la lista.
print(mi_lista)